// One-time recorder, intentionally not a test dependency. Run before removing
// eslint-config-next. The saved diagnostics let CI test parity without installing
// the vulnerable original dependency. Review changes to this record as fixtures.
import { mkdtempSync, mkdirSync, writeFileSync, rmSync, readFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname, resolve } from 'node:path';
import { createRequire } from 'node:module';
import { ESLint } from 'eslint';
import ts from 'typescript-eslint';
import globals from 'globals';
import { cases, routeFiles } from './cases.mjs';

const require = createRequire(process.env.UPSTREAM_ROOT
  ? join(resolve(process.env.UPSTREAM_ROOT),'package.json') : import.meta.url);
const next = require('@next/eslint-plugin-next');
const root = mkdtempSync(join(tmpdir(), 'prompt-info-lint-upstream-'));
for (const file of routeFiles) {
  const path = join(root, file);
  mkdirSync(dirname(path), {recursive:true});
  writeFileSync(path, 'export default function Page() { return null }');
}
const baseline = JSON.parse(readFileSync(new URL('./baseline-config.json', import.meta.url)));
const results = [];
try {
  for (const fixture of cases) {
    const ruleId = `@next/next/${fixture.rule}`;
    const severity = baseline.rules[ruleId][0];
    const eslint = new ESLint({cwd:root, overrideConfigFile:true, overrideConfig:[{
      files:['**/*.{js,jsx,ts,tsx,mjs,mts,cts}'],
      languageOptions:{parser:ts.parser,globals:{...globals.browser,...globals.node}},
      plugins:{'@next/next':next}, rules:{[ruleId]:severity},
    }]});
    const [result] = await eslint.lintText(fixture.code,{filePath:join(root,fixture.filename)});
    if (result.messages.some(m=>m.fatal)) throw new Error(`${fixture.name}: parse failure`);
    const diagnostics=result.messages.map(m=>({rule:m.ruleId.replace('@next/next/',''),severity:m.severity}));
    if (diagnostics.length !== fixture.expected) console.log('DIFFERENCE',fixture.name,'expected',fixture.expected,'upstream',diagnostics.length);
    results.push({name:fixture.name,diagnostics});
  }
  writeFileSync(new URL('./upstream-diagnostics.json',import.meta.url),JSON.stringify({source:'@next/eslint-plugin-next@16.3.8; generated by record-upstream.mjs',results},null,2)+'\n');
  console.log(`Recorded ${results.length} differential fixtures`);
} finally { rmSync(root,{recursive:true,force:true}); }
